import json
import httpx
import asyncio
import time
from datetime import datetime
from typing import List, Optional
from pathlib import Path


async def create_golden_dataset(
    questions: List[str],
    api_url: str,
    database_name: str,
    user_id: str,
    facm_code: List[str],
    output_file: str,
    chat_history: str = "",
):
    """
    Generate a golden dataset by invoking the chat-completion API for a list of questions.
    The results are saved in JSONL format, which can be reviewed and manually labeled.

    Args:
        questions: List of user questions to invoke the API with.
        api_url: Base URL of the API (e.g., "http://localhost:8000/convai")
        database_name: Target database name.
        user_id: The ID of the user making the request.
        facm_code: List of facility codes.
        output_file: Path to the output JSONL file.
        chat_history: Optional chat history to include in the request.
    """
    endpoint = f"{api_url.rstrip('/')}/AI/chat-completion"
    
    # Ensure the parent directory for output file exists
    output_path = Path(output_file)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    results = []
    history_pairs = []

    async with httpx.AsyncClient(timeout=120.0) as client:
        for index, question in enumerate(questions):
            print(f"[{index + 1}/{len(questions)}] Processing question: {question}")
            
            # Build chat history from up to the last 3 questions
            recent_history = history_pairs[-3:]
            current_chat_history = ", ".join([f"user: {q}, ai: {a}" for q, a in recent_history])
            # If an initial chat_history was passed, prepend it if there is no recent history yet, 
            # or just rely on the dynamic history for subsequent questions.
            if not current_chat_history:
                current_chat_history = chat_history

            payload = {
                "database_name": database_name,
                "user_input": question,
                "user_id": user_id,
                "facm_code": facm_code,
                "chat_history": current_chat_history,
                "eval_mode": True,
            }

            try:
                start_time = time.time()
                response = await client.post(endpoint, json=payload)
                response.raise_for_status()
                elapsed = time.time() - start_time
                
                # The response content is JSON in eval_mode
                data = response.json()
                assistant_response = data.get("assistant_response", "")

                case = {
                    "case_id": f"{index:04d}",
                    "timestamp": datetime.utcnow().isoformat(),
                    "database_name": database_name,
                    "user_id": user_id,
                    "user_input": question,
                    "chat_history_sent": current_chat_history,
                    "knowledge_base_examples": data.get("context_for_sql_generation", ""),
                    "generated_sql": data.get("generated_sql", ""),
                    "assistant_response": assistant_response,
                    "latency_ms": round(elapsed * 1000, 1),
                    "status": "success",
                    # empty fields for the QA team to fill in
                    "expected_sql": "",
                    "expected_response": "",
                    "label": "",            # pass / fail
                    "failure_category": "", # retrieval / sql / hallucination / formatting / other
                    "reviewer_notes": "",
                }

                # Write incrementally to the file
                with open(output_path, "a", encoding="utf-8") as f:
                    f.write(json.dumps(case) + "\n")

                results.append(case)
                
                # Add to history for the next iteration
                history_pairs.append((question, assistant_response.strip()))
                
                print(f"  -> Success. Latency: {elapsed:.2f}s. Answer preview: {assistant_response[:50]}...")
                
            except httpx.HTTPStatusError as e:
                print(f"  -> Error: API returned status {e.response.status_code}")
                print(f"  -> Detail: {e.response.text}")
            except Exception as e:
                print(f"  -> Unexpected error: {str(e)}")

            # Brief pause to avoid overwhelming the API or triggering rate limits
            await asyncio.sleep(1)

    print(f"\nFinished! Dataset saved to {output_path}")
    return results

